/**
 * Build the two shipped artifacts.
 *
 * Two rules make this build different from a normal one:
 *   - the Host bundle is NOT minified. The Typert Gateway reads a Remote
 *     method's parameter names back out of the function source text, so
 *     mangling them silently breaks every settings-page call;
 *   - `@deepseek-ai/*` specifiers stay external on both halves: the Harness
 *     resolves them from its own installation, and the browser module table
 *     supplies `react`.
 *
 * @module dsh-roundtable-harness/scripts/build
 */

import { mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Host externals: the Harness supplies these, the profile supplies `docx`. */
export const HOST_EXTERNAL = ['@deepseek-ai/*', 'docx'];
/** Client externals: the browser module table supplies exactly `react`. */
export const CLIENT_EXTERNAL = ['react'];

const HOST_BANNER = `/**
 * dsh-roundtable-harness — Host half (generated by scripts/build.mjs from src/).
 * Do not edit: edit src/ instead.
 */`;

const CLIENT_BANNER = `/**
 * dsh-roundtable-harness — client half (generated by scripts/build.mjs from src/client.tsx).
 * Do not edit: edit src/client.tsx instead.
 */
window.__ModuleLoader__.load({
  id: 'dsh-roundtable-harness',
  factory: (require) => {
    var module = { exports: {} }; var exports = module.exports;`;

const CLIENT_FOOTER = `    return module.exports;
  }
});`;

/**
 * Bundle both halves.
 * @param options - `esbuild` is injected so callers control module resolution.
 * @returns the written output paths.
 */
export async function build(options = {}) {
  let esbuild = options.esbuild;
  if (esbuild === undefined) {
    esbuild = await import('esbuild').catch(() => undefined);
  }
  if (esbuild === undefined) {
    throw new Error('esbuild 未安装：请先运行 pnpm install（或 npm install esbuild）。');
  }
  const logLevel = options.logLevel ?? 'info';
  mkdirSync(resolve(root, 'lib'), { recursive: true });

  const host = await esbuild.build({
    absWorkingDir: root,
    entryPoints: ['src/index.ts'],
    outfile: 'lib/index.js',
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node20',
    external: HOST_EXTERNAL,
    // Load-bearing: Remote parameter names are read from the function source.
    minify: false,
    keepNames: true,
    sourcemap: false,
    banner: { js: HOST_BANNER },
    logLevel,
  });

  const client = await esbuild.build({
    absWorkingDir: root,
    entryPoints: ['src/client.tsx'],
    outfile: 'lib/client.js',
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: 'es2020',
    jsx: 'transform',
    external: CLIENT_EXTERNAL,
    // The launcher artwork is imported as a PNG and inlined by the bundler, so the
    // repository carries a normal image file instead of a 30 KB base64 literal.
    loader: { '.png': 'dataurl' },
    minify: false,
    sourcemap: false,
    banner: { js: CLIENT_BANNER },
    footer: { js: CLIENT_FOOTER },
    logLevel,
  });

  return { host, client, outfiles: [resolve(root, 'lib/index.js'), resolve(root, 'lib/client.js')] };
}

const invokedDirectly = process.argv[1] !== undefined
  && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));

if (invokedDirectly) {
  const { outfiles } = await build();
  for (const path of outfiles) console.log(`[build] 已生成 ${path}`);
}
